export function dayKey(date = new Date()) {
  if (!(date instanceof Date) || !Number.isFinite(date.getTime())) throw new RangeError('Invalid day');
  return [date.getFullYear(), String(date.getMonth() + 1).padStart(2, '0'), String(date.getDate()).padStart(2, '0')].join('-');
}
function ordinal(key) {
  if (typeof key !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(key)) return null;
  const [year, month, day] = key.split('-').map(Number);
  if (year < 2000 || year > 2200) return null;
  const date = new Date(Date.UTC(year, month - 1, day));
  return date.getUTCFullYear() === year && date.getUTCMonth() === month - 1 && date.getUTCDate() === day ? date.getTime() / 86400000 : null;
}
const count = value => Number.isInteger(value) && value >= 0 && value <= 1000000 ? value : 0;
export function normalizeLearning(value) {
  if (!value || typeof value !== 'object' || ordinal(value.lastDay) === null) return { lastDay: null, score: 0, streak: 0, bestStreak: 0, sessions: 0 };
  const streak = count(value.streak);
  return { lastDay: value.lastDay, score: value.score === 1 ? 1 : 0, streak,
    bestStreak: Math.max(streak, count(value.bestStreak)), sessions: count(value.sessions) };
}
export function dailyChallenge(date = new Date()) {
  const key = dayKey(date);
  return { ...CHALLENGES[ordinal(key) % CHALLENGES.length], day: key };
}
export function completeChallenge(previous, date, score) {
  const state = normalizeLearning(previous);
  const today = dayKey(date);
  if (state.lastDay === today) return state;
  const consecutive = ordinal(today) - ordinal(state.lastDay) === 1 && state.lastDay !== null;
  const streak = consecutive ? Math.min(state.streak + 1, 1000000) : 1;
  return { lastDay: today, score: score === 1 ? 1 : 0, streak,
    bestStreak: Math.max(streak, state.bestStreak), sessions: Math.min(state.sessions + 1, 1000000) };
}
export function activeStreak(previous, date = new Date()) {
  const state = normalizeLearning(previous);
  const gap = state.lastDay ? ordinal(dayKey(date)) - ordinal(state.lastDay) : null;
  return gap === 0 || gap === 1 ? state.streak : 0;
}
